NAMES = {"logistic": "Logistic regression", "lightgbm": "LightGBM"}
TAGS = {"with_early_citations": "with early citations", "without_early_citations": "without early citations"}


def fmt_ci(t, pct=False, d=3) -> str:
    s = 100 if pct else 1
    u = " pp" if pct else ""
    return f"{t[0]*s:.{d if not pct else 1}f}{u} (95% CI {t[1]*s:.{d if not pct else 1}f} to {t[2]*s:.{d if not pct else 1}f})"


def rank_findings(cands: list[dict]) -> list[dict]:
    """Supported = CI excludes the null value. Ranked by standardized distance from the null
    (|estimate - null| / approx. SE), unsupported ones last."""
    for c in cands:
        est, lo, hi, null = c["est"], c["lo"], c["hi"], c["null"]
        c["supported"] = not (lo <= null <= hi)
        se = max((hi - lo) / 3.92, 1e-12)
        c["z"] = abs(est - null) / se
    return sorted(cands, key=lambda c: (not c["supported"], -c["z"]))


def ledger_total(ledger: Path) -> tuple[float | None, int]:
    if not ledger.exists():
        return None, 0
    rows = [json.loads(l) for l in ledger.read_text().splitlines() if l.strip()]
    usd = [r["spent_usd"] for r in rows if r.get("spent_usd") is not None]
    return (sum(usd) if usd else None), sum(r.get("network_calls", 0) for r in rows)


def write_results(path: Path, ctx: dict) -> list[dict]:
    m, ga = ctx["res"]["metrics"], ctx["ga"]
    lg = m[("lightgbm", "without_early_citations")]
    cands = [
        {"title": "Early signals carry predictive information about reaching the top 5% (held-out cohorts)",
         "number": f"LightGBM ROC-AUC without early citations = {fmt_ci(lg['roc_auc'])}; null = 0.5",
         "est": lg["roc_auc"][0], "lo": lg["roc_auc"][1], "hi": lg["roc_auc"][2], "null": 0.5},
        {"title": "Authors with a top early coauthor are more likely to reach the top 5%",
         "number": f"P(top 5%) difference, coauthor vs none, all cohort members with a known tier group = "
                   f"{fmt_ci(ga['overall_gap'], pct=True)}; adjusted log-odds (standardized logistic) = {fmt_ci(ctx['adj'])}",
         "est": ga["overall_gap"][0], "lo": ga["overall_gap"][1], "hi": ga["overall_gap"][2], "null": 0.0},
        {"title": "The top-coauthor advantage is larger at lower-ranked institutions",
         "number": f"Difference-in-differences (lower-ranked gap minus top-ranked gap) = {fmt_ci(ga['did'], pct=True)}; "
                   f"gap at top-ranked = {fmt_ci(ga['gap_top'], pct=True)}, at lower-ranked = {fmt_ci(ga['gap_lower'], pct=True)}",
         "est": ga["did"][0], "lo": ga["did"][1], "hi": ga["did"][2], "null": 0.0},
    ]
    ranked = rank_findings(cands)
    L = [f"# Results\n", f"Run date: {ctx['run_date']}  |  mode: {'DRY RUN (not a result)' if ctx['dry_run'] else 'full run'}\n",
         "All numbers below are generated by `python -m src.pipeline`. Nothing is hand-edited.\n"]
    if ctx["dry_run"]:
        L.append("> **DRY RUN**: sample is far too small for any inference. Use only to check the pipeline.\n")

    L += ["## Cohort\n", f"- Final cohort: **{ctx['n_cohort']:,}** authors (t0 = first indexed publication year 2008-2011, "
          f">= {config.MIN_EARLY_WORKS} works in t0..t0+2). Target range was {config.TARGET_COHORT[0]:,}-{config.TARGET_COHORT[1]:,}.",
          f"- Funnel: {json.dumps(ctx['funnel'])}",
          f"- Top-5% threshold: citations_15 >= {ctx['threshold']:.0f}; positives: {ctx['n_pos']:,} ({ctx['n_pos']/ctx['n_cohort']*100:.1f}%).",
          f"- Train (t0 2008-09): {ctx['res']['n_train']:,}; test (t0 2010-11): {ctx['res']['n_test']:,}.",
          f"- Authors with no works in t0..t0+14 beyond the early window are kept (label 0 unless citations qualify). "
          f"Share with zero late-period papers: {ctx['share_stopped']*100:.1f}%.\n",
          "## Features (log)\n",
          f"- Share with a top coauthor: {ctx['feat_log']['share_has_top_coauthor']*100:.1f}% "
          f"(top 5% of {ctx['feat_log']['n_coauthors_with_h']:,} coauthors with h-index; h >= {ctx['feat_log']['top_coauthor_h_threshold']:.0f}).",
          f"- Institution tier unknown: {ctx['feat_log']['share_unknown_institution']*100:.1f}% (own category).",
          f"- Top-venue citedness threshold (top 10% in dataset): {ctx['feat_log']['venues']['citedness_threshold']:.2f}.",
          "- Hand-listed venue matches (papers in cohort):"]
    for k, v in ctx["feat_log"]["venues"]["hand"].items():
        L.append(f"  - {k}: " + (", ".join(f"{x['name']} ({x['papers_in_cohort']})" for x in v) if v else "**no match in OpenAlex data**"))
    L += ["- Stricter pre-collaboration top-coauthor definition: **not implemented** (would need per-coauthor works counts by year).\n",
          "## Model performance (test: t0 2010-11)\n",
          "| Model | Features | ROC-AUC (95% CI) | PR-AUC (95% CI) | Base rate | N test |", "|---|---|---|---|---|---|"]
    for (name, tag), v in m.items():
        L.append(f"| {NAMES[name]} | {TAGS[tag]} | {fmt_ci(v['roc_auc'])} | {fmt_ci(v['pr_auc'])} | {v['base_rate']:.3f} | {v['n']:,} |")
    L += ["\nSHAP and the interaction plot use the LightGBM model *without* early citations (less overlap with the target).\n",
          "## Top coauthor x institution tier (model-free, whole cohort)\n",
          "| Institution group | Top coauthor | n | n in top 5% | P(top 5%) (95% CI) |", "|---|---|---|---|---|"]
    for r in ga["table"].itertuples():
        L.append(f"| {r.tier_group} | {'yes' if r.has_top_coauthor else 'no'} | {r.n:,} | {r.n_top5} | "
                 f"{r.p_top5*100:.1f}% ({r.ci_low*100:.1f}-{r.ci_high*100:.1f}) |")
    L += [f"\nExcluded from this table (tier 2 or unknown institution): {ga['n_excluded_mid_or_unknown']:,}.",
          f"- Gap at top-ranked institutions: {fmt_ci(ga['gap_top'], pct=True)}",
          f"- Gap at lower-ranked institutions: {fmt_ci(ga['gap_lower'], pct=True)}",
          f"- Difference-in-differences: {fmt_ci(ga['did'], pct=True)}",
          f"- Adjusted effect of top coauthor (log-odds, standardized logistic, bootstrap): {fmt_ci(ctx['adj'])}",
          f"- Agreement with Li et al. 2019 (Nature Communications; early collaboration with a top scientist is associated with higher later success): **{ctx['li']}**.\n",
          "## Model view: push from a top coauthor, by institution group (test cohorts, authors with a top coauthor)\n",
          "Descriptive: the CIs only reflect averaging over the n authors for a fixed model (they ignore model and sampling uncertainty) and must not be read as a significance test; use the model-free table above.\n",
          "| Institution group | n | Mean SHAP of top coauthor (95% CI) | Mean interaction with institution rank (95% CI) |",
          "|---|---|---|---|"]
    for r in ctx["inter"].itertuples():
        L.append(f"| {r.tier_group} | {r.n} | {r.shap:.2f} ({r.shap_lo:.2f} to {r.shap_hi:.2f}) | "
                 f"{r.interaction:.2f} ({r.interaction_lo:.2f} to {r.interaction_hi:.2f}) |")
    L += ["",
          "## Secondary target\n",
          f"- h-index over t0..t0+14 (median / 95th pct): {ctx['h_med']:.0f} / {ctx['h_p95']:.0f}. Not modeled further (classification is the primary task).\n",
          "## Candidate headline findings, ranked by robustness\n",
          "Ranking: findings whose 95% CI excludes the null come first, ordered by |estimate - null| / approximate SE. "
          "A finding whose CI crosses the null is marked **not supported**.\n"]
    for i, c in enumerate(ranked, 1):
        L.append(f"{i}. **{c['title']}** - {'supported' if c['supported'] else '**not supported** (CI crosses null)'}  \n"
                 f"   Evidence: {c['number']}")
    L.append("\nFigures: `figures/` (see README).")
    Path(path).write_text("\n".join(L) + "\n", encoding="utf-8")
    return ranked


def write_limitations(path: Path, ctx: dict) -> None:
    f = ctx["feat_log"]
    txt = f"""# Limitations

- **Correlation, not causation.** Top researchers choose collaborators, and strong students choose (or are chosen by) strong groups. Nothing here estimates the causal effect of a coauthor.
- **Remaining survivorship bias.** Authors who stopped publishing are kept with label 0, but only if OpenAlex indexed at least {config.MIN_EARLY_WORKS} works in their first three years. Careers that never produced two indexed early papers are invisible. The cohort is also built from authors on a *sample* of AI works, which over-represents prolific authors.
- **Author disambiguation errors.** OpenAlex merges and splits author profiles. Merges inflate counts and citations; splits shorten apparent careers and can make a senior author look like a newcomer (t0 is the first *indexed* year, not necessarily the first publication).
- **Venue coverage is uneven.** Conferences are inconsistently indexed as sources. Hand-listed venues with no match are reported in results.md (unmatched: {', '.join(f['venues']['hand_unmatched']) or 'none'}); n_top_venue_papers is therefore a lower bound for conference-heavy careers.
- **Current-h-index approximation.** has_top_coauthor uses each coauthor's *current* h-index, which includes work done after the collaboration. A stricter pre-collaboration version was not implemented. Institution tier likewise uses current institution statistics and the author's most frequent *early* affiliation; {f['share_unknown_institution']*100:.1f}% have no institution and form their own category.
- **Shared papers inflate the coauthor effect mechanically.** Papers written with a highly cited coauthor add to the author's own citation total, so part of the top-coauthor association is built into the target. This was not separated out.
- **Current citation totals.** The target counts citations accumulated up to the data date for papers published in t0..t0+14, so earlier-published work has had more time to be cited than a strict 15-year snapshot. early_citations overlaps the target; models are reported with and without it.
- **Top-5% label is relative to this cohort** (threshold {ctx['threshold']:.0f} citations) and sensitive to field-level citation inflation in 2008-2025.
- **Single field, single database.** Artificial Intelligence (OpenAlex subfield 1702) only; no cross-field normalization and no claim that results generalize to other fields or to databases such as Scopus or Google Scholar.
- **Multiple comparisons / small cells.** The 2x2 comparison splits the cohort into four groups; cells with few top-5% members have wide intervals. Confidence intervals are bootstrap percentile intervals and ignore author non-independence (shared papers).
"""
    Path(path).write_text(txt, encoding="utf-8")
